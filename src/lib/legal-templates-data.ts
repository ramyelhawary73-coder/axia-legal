/**
 * Maps a client's profile fields directly to template variables
 */
export function extractClientTemplateVariables(client: Client, matter?: Matter): Record<string, string> {
  const today = new Date();
  const formattedToday = `${today.getFullYear()}/${String(today.getMonth() + 1).padStart(2, "0")}/${String(today.getDate()).padStart(2, "0")}`;

  const vars: Record<string, string> = {
    client_name: client.name || "",
    client_type: client.type || "",
    client_id_or_cr: client.nationalIdOrCr || "",
    client_address: client.address || "",
    client_phone: client.phone || "",
    client_email: client.email || "",
    poa_number: client.poaNumber || "",
    poa_office: client.poaOffice || "",
    notice_date: formattedToday,
    contract_date: formattedToday,
    petition_date: formattedToday,
    clearance_date: formattedToday,
    lawyer_name: "د. رامي الهواري المحامي بالنقض والدستورية العليا - 14 شارع عبد الخالق ثروت، وسط البلد، القاهرة",
    bailiff_court: "محكمة قصر النيل الجزئية",
  };

  // If a matter is associated, auto-fill case/opponent details
  if (matter) {
    vars.case_number = matter.caseNumber || "";
    vars.court_name = matter.court || "";
    vars.circuit_name = matter.circuit || "";
    vars.opponent_name = matter.opponentName || "";
    vars.claim_amount = matter.claimAmount || "";
    vars.hearing_date = matter.nextHearingDate || "";
    vars.client_role = matter.clientRole || "مدعي";
    vars.lawyer_name = `${matter.assignedLawyer} - مكتب د. رامي الهواري للمحاماة`;
  }

  return vars;
}

/**
 * Replaces all {{key}} instances in a template body with provided variable values
 */
export function renderLegalTemplate(templateBody: string, variables: Record<string, string>): string {
  return templateBody.replace(/\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g, (_, key) => {
    const val = variables[key];
    if (val !== undefined && val.trim() !== "") {
      return val;
    }
    return `[${key}]`;
  });
}
